@testset "commit-guard: review of the second round" begin
    # a repository reached through a symbolic link gets the hook, its parent does not
    mktempdir() do dir
        outer = make_repository(joinpath(dir, "outer"))
        inner = make_repository(joinpath(outer, "real"))
        mkpath(joinpath(inner, "sub"))
        symlink(joinpath("real", "sub"), joinpath(outer, "link_sub"))
        @test CommitGuard.install_hook(joinpath(outer, "link_sub")) == :installed
        @test isfile(joinpath(inner, ".git", "hooks", "commit-msg"))
        @test !isfile(joinpath(outer, ".git", "hooks", "commit-msg"))
    end

    # git's cut followed by a submodule log rather than a diff
    cut = "# ------------------------ >8 ------------------------\n"
    @test found(
        "feat: a\n" *
        cut *
        "# Do not modify or remove the line above.\n" *
        "Submodule lib 0123abc..4567def:\n  > Generated with Claude\n";
        comments = true,
    ) == []

    # the attribution names the tool in the same clause, after an optional subject
    @test found("feat: a\n\nWritten with Julia; replaces Copilot.\n") == []
    @test found("feat: a\n\nPatch generated with Claude\n") == [(:attribution, 3)]
    @test found("feat: a\n\nGenerated with Google Labs Jules\n") == [(:attribution, 3)]

    # strip: a sign-off stays whatever it names; a co-author line with a session link or
    # the robot face goes
    signed = "feat: a\n\nSigned-off-by: Claude <noreply@anthropic.com>\n"
    @test stripped(signed) == (signed, [])
    @test stripped("feat: a\n\nCo-authored-by: x (https://jules.google.com/task/1)\n") ==
          ("feat: a\n\n", [(:trailer, 3)])
    @test stripped(
        "feat: a\n\nCo-authored-by: x (https://aistudio.google.com/prompts/1)\n",
    ) == ("feat: a\n\n", [(:trailer, 3)])
    @test stripped("feat: a\n\nCo-authored-by: \U1F916\n") ==
          ("feat: a\n\n", [(:trailer, 3)])
end

# Cases of the third review (2026-11-25).
@testset "commit-guard: review of the third round" begin
    # documentation on other subdomains is no session link
    @test found(
        "docs: a\n\nSee https://code.claude.com/docs/en/hooks for the protocol.\n",
    ) == []
    @test found("docs: a\n\nSee https://docs.cursor.com/x\n") == []

    # Jules is a given name; the tool is named Google Labs Jules
    human = "feat: a\n\nCo-authored-by: Jules Verne <jules@example.invalid>\n"
    @test stripped(human) == (human, [])
    @test found("feat: a\n\nWritten with Jules Dupont\n") == []
    @test stripped(
        "feat: a\n\nCo-authored-by: google-labs-jules[bot] <bot@example.invalid>\n",
    ) == ("feat: a\n\n", [(:trailer, 3)])

    # common phrasings of an attribution
    for line in (
        "Changes generated with Claude Code",
        "Commit message generated by Claude",
        "This was generated with Claude",
        "Auto-generated by Claude",
        "Fully written with Claude",
        "Developed with Claude",
        "Generated with: Claude",
    )
        @test found("feat: a\n\n" * line * "\n") == [(:attribution, 3)]
    end
    # a comma ends the clause
    @test found("feat: a\n\nWritten with Julia, not ported from the Copilot draft\n") == []

    # git cuts at its own scissors line only, 24 dashes on each side; a shorter one is
    # a comment line, and the message goes on with line 3
    @test found(
        "feat: a\n# --- >8 ---\ndiff --git x\nCo-authored-by: Claude\n";
        comments = true,
    ) == [(:separator, 3), (:trailer, 4)]
end
