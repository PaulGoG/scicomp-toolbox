# Tests of standalone/commit-guard.jl, included from runtests.jl inside its outer testset.
# The script is loaded into a module of its own: the other standalone scripts define
# functions of the same names at top level.

module CommitGuard
include(joinpath(dirname(@__DIR__), "commit-guard.jl"))
end

const COMMIT_GUARD_SCRIPT = joinpath(dirname(@__DIR__), "commit-guard.jl")

# (rule, line) pairs of the findings of a message
function found(message; kwargs...)
    return [(f.rule, f.line) for f in CommitGuard.check_message(message; kwargs...)]
end

# Exit code and the texts written to `io` and `err` by `CommitGuard.main`
function run_commit_guard(args)
    out = IOBuffer()
    err = IOBuffer()
    code = CommitGuard.main(args; io = out, err = err)
    return code, String(take!(out)), String(take!(err))
end

# Repository with the commits "initial", "feat: clean", "fix: with trailer", "docs: last"
function make_history_repository(repo)
    make_repository(repo)
    git_run(repo, "commit", "--quiet", "--allow-empty", "-m", "feat: clean")
    git_run(
        repo,
        "commit",
        "--quiet",
        "--allow-empty",
        "-m",
        "fix: with trailer\n\nCo-Authored-By: x <x@y.invalid>",
    )
    git_run(repo, "commit", "--quiet", "--allow-empty", "-m", "docs: last")
    return repo
end

@testset "commit-guard: accepted messages" begin
    accepted = [
        "feat: add solver\n",
        "fix(slurm-launch): job scripts start Julia without --project\n\nThe flag is gone.\n",
        "feat(api)!: drop the v1 interface\n\nBREAKING CHANGE: removed.\n",
        "ci: pin actions\n",
        "chore(deps): bump HTTP to 2.16.0\n",
        "feat(hardware-diagnostics, standalone): count physical cores\n",
        "docs: tables generated by PrettyTables\n",
        "feat: support Gemini 4 models in the client\n",
        "docs: describe how figures are generated with Makie\n",
        "refactor: plain wording\n\nWritten with care by the author.\n",
        "fix: cite https://doi.org/10.1000/xyz and " *
        "https://github.com/JuliaLang/julia/pull/1\n",
        "Merge branch 'main' into dev\n",
        "Revert \"feat: add solver\"\n\nThis reverts commit 0123abc.\n",
        "fixup! feat: add solver\n",
        "squash! feat: add solver\n",
        "amend! feat: add solver\n",
    ]
    for message in accepted
        @test found(message) == []
    end
end

@testset "commit-guard: header" begin
    rejected = [
        "Add solver\n",
        "feat:missing space\n",
        "Feat: capital type\n",
        "feature: unknown type\n",
        "feat(): empty scope\n",
        "feat( ): blank scope\n",
        "fix: \n",
        "feat (api): space before the scope\n",
    ]
    for message in rejected
        @test found(message) == [(:header, 1)]
    end
    @test found("\n\nupdate things\n") == [(:header, 3)]
end

@testset "commit-guard: separator" begin
    message = "feat: a\nbody without a blank line\n"
    @test found(message) == [(:separator, 2)]
    @test only(CommitGuard.check_message(message)).text == "body without a blank line"
end

@testset "commit-guard: trailers" begin
    @test found("feat: a\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n") ==
          [(:trailer, 3)]
    @test found("fix: b\n\nSigned-off-by: A B <a@b.invalid>\n") == [(:trailer, 3)]
    @test found("fix: b\n\nco-authored-by: someone <s@t.invalid>\n") == [(:trailer, 3)]
    @test found("\n\nfeat: a\n\nSigned-off-by: x\n") == [(:trailer, 5)]
end

@testset "commit-guard: attribution" begin
    @test found(
        "feat: a\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n",
    ) == [(:attribution, 3)]
    @test found("docs: b\n\nGenerated by Gemini\n") == [(:attribution, 3)]
    @test found("feat: c\n\nAssisted-by: some tool\n") == [(:attribution, 3)]
    @test found("feat: d\n\nWritten by an AI assistant.\n") == [(:attribution, 3)]
    @test found("fix: e, co-authored with Copilot\n") == [(:attribution, 1)]
end

@testset "commit-guard: session links" begin
    @test found("fix: d\n\nhttps://claude.ai/code/session_01ABC\n") == [(:session_url, 3)]
    @test found("fix: d\n\nSee https://chatgpt.com/share/abc for the discussion.\n") ==
          [(:session_url, 3)]
    @test found("fix: d\n\nhttps://gemini.google.com/share/xyz\n") == [(:session_url, 3)]
end

@testset "commit-guard: several findings" begin
    message = "update\nbody\n\nCo-Authored-By: x <x@y.invalid>\nhttps://claude.ai/code/s\n"
    @test found(message) ==
          [(:header, 1), (:separator, 2), (:trailer, 4), (:session_url, 5)]
end

@testset "commit-guard: message files" begin
    plain = "feat: a\n# Please enter the commit message\n# Co-Authored-By: x\n"
    scissors =
        "feat: a\n# ------------------------ >8 ------------------------\n" *
        "diff --git a/x b/x\n+Co-Authored-By: y\n"
    @test found(plain; comments = true) == []
    @test found(scissors; comments = true) == []
    @test first(found(plain)) == (:separator, 2)
    @test first(found(scissors)) == (:separator, 2)
    @test found("# only a comment\n"; comments = true) == [(:empty, 0)]
    @test found("") == [(:empty, 0)]
    @test found("  \n\n") == [(:empty, 0)]
end

@testset "commit-guard: rule selection" begin
    message = "update\n\nSigned-off-by: x\n"
    @test found(message; rules = (:trailer,)) == [(:trailer, 3)]
    @test found(message; rules = (:header,)) == [(:header, 1)]
    @test_throws ArgumentError CommitGuard.check_message("feat: a"; rules = (:nonsense,))
end

@testset "commit-guard: history" begin
    mktempdir() do dir
        repo = make_history_repository(joinpath(dir, "repo"))
        h = CommitGuard.check_history(repo)
        @test length(h) == 2
        @test [(f.rule, f.line) for f in last(first(h))] == [(:trailer, 3)]
        @test :header in [f.rule for f in last(last(h))]
        @test all(p -> length(first(p)) == 40 && all(isxdigit, first(p)), h)
        @test length(
            CommitGuard.check_history(repo; rules = (:trailer, :attribution, :session_url)),
        ) == 1
        @test CommitGuard.check_history(repo, "HEAD~1..HEAD") == []
        @test_throws ArgumentError CommitGuard.check_history(repo, "no-such-ref")
        @test_throws ArgumentError CommitGuard.check_history(mktempdir())
    end
end

@testset "commit-guard: command line" begin
    mktempdir() do dir
        clean = joinpath(dir, "clean.txt")
        write(clean, "feat: a\n")
        @test run_commit_guard(["check", clean]) == (0, "", "")
        @test first(run_commit_guard([clean])) == 0

        bad = joinpath(dir, "bad.txt")
        write(bad, "update\n\nSigned-off-by: x\n")
        code, _, err = run_commit_guard([bad])
        @test code == 1
        @test occursin("commit-guard: header: line 1: update", err)
        @test occursin("commit-guard: trailer: line 3: Signed-off-by: x", err)
        @test occursin("Co-authored-by and Signed-off-by trailers are not used", err)
        @test occursin("commit refused", err)

        code, _, err = run_commit_guard(["check", bad, "--rules", "trailer"])
        @test code == 1
        @test !occursin("header", err)

        repo = make_history_repository(joinpath(dir, "repo"))
        code, out, _ = run_commit_guard(["log", "--repo", repo])
        @test code == 1
        @test occursin("2 of 4 commits with findings", out)
        _, out, _ = run_commit_guard(["log", "--repo", repo, "--rules", "trailer"])
        @test occursin("1 of 4", out)
        code, out, _ = run_commit_guard(["log", "HEAD~1..HEAD", "--repo", repo])
        @test code == 0
        @test occursin("0 of 1 commits with findings", out)

        @test first(run_commit_guard(["--help"])) == 0
        @test first(run_commit_guard(String[])) == 2
        @test first(run_commit_guard(["check"])) == 2
        @test first(run_commit_guard(["check", joinpath(dir, "absent")])) == 2
        @test first(run_commit_guard(["frobnicate", "x", "y"])) == 2
        @test first(run_commit_guard(["check", clean, "--rules", "nonsense"])) == 2
    end
end

@testset "commit-guard: hook" begin
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        hook = joinpath(repo, ".git", "hooks", "commit-msg")
        script = read(COMMIT_GUARD_SCRIPT)

        @test CommitGuard.install_hook(repo) == :installed
        @test isfile(hook)
        @test uperm(hook) & 0x01 != 0
        @test read(hook) == script
        @test CommitGuard.install_hook(repo) == :current

        write(hook, "#!/bin/sh\n# commit-guard hook\nexit 0\n")
        @test CommitGuard.install_hook(repo) == :updated
        @test read(hook) == script

        foreign = "#!/bin/sh\nexit 0\n"
        write(hook, foreign)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test read(hook, String) == foreign
        @test CommitGuard.install_hook(repo; force = true) == :installed
        @test read(hook * ".backup", String) == foreign
        write(hook, foreign)
        @test_throws ArgumentError CommitGuard.install_hook(repo; force = true)

        @test_throws ArgumentError CommitGuard.install_hook(mktempdir())

        # a hooks directory outside the repository is never written to
        shared = mkpath(joinpath(dir, "shared-hooks"))
        git_run(repo, "config", "--local", "core.hooksPath", shared)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test_throws ArgumentError CommitGuard.install_hook(repo; force = true)
        @test isempty(readdir(shared))
        @test first(run_commit_guard(["install", repo])) == 2
        git_run(repo, "config", "--local", "--unset", "core.hooksPath")

        # the hook at work, with the running Julia first on PATH
        rm(hook)
        CommitGuard.install_hook(repo)
        withenv("PATH" => Sys.BINDIR * ":" * ENV["PATH"]) do
            commit(message) = begin
                cmd = `git -C $repo -c user.name=Test -c user.email=test@example.invalid -c commit.gpgsign=false commit --quiet --allow-empty -m $message`
                success(pipeline(ignorestatus(cmd); stdout = devnull, stderr = devnull))
            end
            @test !commit("update things")
            @test !commit("feat: x\n\nCo-Authored-By: y <y@z.invalid>")
            @test commit("feat: accepted by the hook")
        end
        @test read(`git -C $repo log -1 --format=%s`, String) ==
              "feat: accepted by the hook\n"

        code, out, _ = run_commit_guard(["install", repo])
        @test code == 0
        @test occursin("hook current at", out)
    end
end
