# Tests of standalone/commit-guard.jl, included from runtests.jl inside its outer testset.
# The script is loaded into a module of its own: the other standalone scripts define
# functions of the same names at top level.

module CommitGuard
include(joinpath(dirname(@__DIR__), "commit-guard.jl"))
end

const COMMIT_GUARD_SCRIPT = joinpath(dirname(@__DIR__), "commit-guard.jl")

# (rule, line) pairs of the findings of a message
function found(message; kwargs...)
    return [(f.rule, f.line) for f in CommitGuard.check_message(message; kwargs...)]
end

# Exit code and the texts written to `io` and `err` by `CommitGuard.main`
function run_commit_guard(args)
    out = IOBuffer()
    err = IOBuffer()
    code = CommitGuard.main(args; io = out, err = err)
    return code, String(take!(out)), String(take!(err))
end

# Message left by `strip_message` and the (rule, line) pairs of the removed lines
function stripped(message; kwargs...)
    result = CommitGuard.strip_message(message; kwargs...)
    return first(result), [(f.rule, f.line) for f in last(result)]
end

# Repository with the commits "initial", "feat: clean", "fix: with trailer", "docs: last"
function make_history_repository(repo)
    make_repository(repo)
    git_run(repo, "commit", "--quiet", "--allow-empty", "-m", "feat: clean")
    git_run(
        repo,
        "commit",
        "--quiet",
        "--allow-empty",
        "-m",
        "fix: with trailer\n\nCo-Authored-By: x <x@y.invalid>",
    )
    git_run(repo, "commit", "--quiet", "--allow-empty", "-m", "docs: last")
    return repo
end

