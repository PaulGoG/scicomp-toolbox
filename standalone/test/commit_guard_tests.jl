@testset "commit-guard: hook modes" begin
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        CommitGuard.install_hook(repo)
        attributed = "update things\n\nCo-authored-by: Claude <noreply@anthropic.com>\nKept."
        last_message() = read(`git -C $repo log -1 --format=%B`, String)
        withenv("PATH" => Sys.BINDIR * ":" * ENV["PATH"]) do
            commit(message) = begin
                cmd = `git -C $repo -c user.name=Test -c user.email=test@example.invalid -c commit.gpgsign=false commit --quiet --allow-empty -m $message`
                success(pipeline(ignorestatus(cmd); stdout = devnull, stderr = devnull))
            end
            @test !commit(attributed)

            git_run(repo, "config", "--local", "commit-guard.mode", "strip")
            @test commit(attributed)
            @test strip(last_message()) == "update things\n\nKept."
            @test !occursin("Co-authored-by", last_message())

            pair = "feat: pair work\n\nCo-authored-by: Jane Doe <jane@example.invalid>"
            @test commit(pair)
            @test occursin("Co-authored-by: Jane Doe", last_message())

            git_run(repo, "config", "--local", "commit-guard.mode", "refuse")
            @test !commit(attributed)

            git_run(repo, "config", "--local", "commit-guard.mode", "nonsense")
            @test !commit("feat: fine")

            git_run(repo, "config", "--local", "--unset", "commit-guard.mode")
            @test commit("feat: fine")
        end
    end
end

