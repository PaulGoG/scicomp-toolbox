@testset "commit-guard: command line" begin
    mktempdir() do dir
        clean = joinpath(dir, "clean.txt")
        write(clean, "feat: a\n")
        @test run_commit_guard(["check", clean]) == (0, "", "")
        @test first(run_commit_guard([clean])) == 0

        bad = joinpath(dir, "bad.txt")
        write(bad, "update\n\nSigned-off-by: x\n")
        code, _, err = run_commit_guard([bad])
        @test code == 1
        @test occursin("commit-guard: header: line 1: update", err)
        @test occursin("commit-guard: trailer: line 3: Signed-off-by: x", err)
        @test occursin(
            "Co-authored-by, Co-developed-by and Signed-off-by trailers are not used",
            err,
        )
        @test occursin("commit refused", err)

        code, _, err = run_commit_guard(["check", bad, "--rules", "trailer"])
        @test code == 1
        @test !occursin("header", err)

        repo = make_history_repository(joinpath(dir, "repo"))
        code, out, _ = run_commit_guard(["log", "--repo", repo])
        @test code == 1
        @test occursin("2 of 4 commits with findings", out)
        _, out, _ = run_commit_guard(["log", "--repo", repo, "--rules", "trailer"])
        @test occursin("1 of 4", out)
        code, out, _ = run_commit_guard(["log", "HEAD~1..HEAD", "--repo", repo])
        @test code == 0
        @test occursin("0 of 1 commits with findings", out)

        @test first(run_commit_guard(["--help"])) == 0
        @test first(run_commit_guard(String[])) == 2
        @test first(run_commit_guard(["check"])) == 2
        @test first(run_commit_guard(["check", joinpath(dir, "absent")])) == 2
        @test first(run_commit_guard(["frobnicate", "x", "y"])) == 2
        @test first(run_commit_guard(["check", clean, "--rules", "nonsense"])) == 2
    end
end

@testset "commit-guard: hook" begin
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        hook = joinpath(repo, ".git", "hooks", "commit-msg")
        script = read(COMMIT_GUARD_SCRIPT)

        @test CommitGuard.install_hook(repo) == :installed
        @test isfile(hook)
        @test uperm(hook) & 0x01 != 0
        @test read(hook) == script
        @test CommitGuard.install_hook(repo) == :current

        write(hook, "#!/bin/sh\n# commit-guard hook\nexit 0\n")
        @test CommitGuard.install_hook(repo) == :updated
        @test read(hook) == script

        foreign = "#!/bin/sh\nexit 0\n"
        write(hook, foreign)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test read(hook, String) == foreign
        @test CommitGuard.install_hook(repo; force = true) == :installed
        @test read(hook * ".backup", String) == foreign
        write(hook, foreign)
        @test_throws ArgumentError CommitGuard.install_hook(repo; force = true)

        @test_throws ArgumentError CommitGuard.install_hook(mktempdir())

        # a hooks directory outside the repository is never written to
        shared = mkpath(joinpath(dir, "shared-hooks"))
        git_run(repo, "config", "--local", "core.hooksPath", shared)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test_throws ArgumentError CommitGuard.install_hook(repo; force = true)
        @test isempty(readdir(shared))
        @test first(run_commit_guard(["install", repo])) == 2
        git_run(repo, "config", "--local", "--unset", "core.hooksPath")

        # the hook at work, with the running Julia first on PATH
        rm(hook)
        CommitGuard.install_hook(repo)
        withenv("PATH" => Sys.BINDIR * ":" * ENV["PATH"]) do
            commit(message) = begin
                cmd = `git -C $repo -c user.name=Test -c user.email=test@example.invalid -c commit.gpgsign=false commit --quiet --allow-empty -m $message`
                success(pipeline(ignorestatus(cmd); stdout = devnull, stderr = devnull))
            end
            @test !commit("update things")
            @test !commit("feat: x\n\nCo-Authored-By: y <y@z.invalid>")
            @test commit("feat: accepted by the hook")
        end
        @test read(`git -C $repo log -1 --format=%s`, String) ==
              "feat: accepted by the hook\n"

        code, out, _ = run_commit_guard(["install", repo])
        @test code == 0
        @test occursin("hook current at", out)
    end

    # the marker counts on the second line only
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        hook = joinpath(repo, ".git", "hooks", "commit-msg")
        other = "#!/bin/sh\nother-check \"\$1\"\n# commit-guard hook\n"
        write(hook, other)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test read(hook, String) == other
    end

    # an installed hook that lost its execute bit is restored
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        hook = joinpath(repo, ".git", "hooks", "commit-msg")
        CommitGuard.install_hook(repo)
        chmod(hook, 0o644)
        @test CommitGuard.install_hook(repo) == :updated
        @test uperm(hook) & 0x01 != 0
    end

    # a hooks directory that is a link is never written to
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        shared = mkpath(joinpath(dir, "shared"))
        foreign = "#!/bin/sh\nexit 0\n"
        write(joinpath(shared, "commit-msg"), foreign)
        rm(joinpath(repo, ".git", "hooks"); recursive = true)
        symlink(shared, joinpath(repo, ".git", "hooks"))
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test_throws ArgumentError CommitGuard.install_hook(repo; force = true)
        @test readdir(shared) == ["commit-msg"]
        @test read(joinpath(shared, "commit-msg"), String) == foreign
    end

    # a dangling hook link is someone else's hook and is moved, not followed
    mktempdir() do dir
        repo = make_repository(joinpath(dir, "repo"))
        hook = joinpath(repo, ".git", "hooks", "commit-msg")
        mkpath(joinpath(repo, "tools"))
        symlink(joinpath("..", "..", "tools", "commit-msg"), hook)
        @test_throws ArgumentError CommitGuard.install_hook(repo)
        @test isempty(readdir(joinpath(repo, "tools")))
        @test CommitGuard.install_hook(repo; force = true) == :installed
        @test islink(hook * ".backup")
        @test !islink(hook)
        @test read(hook) == read(COMMIT_GUARD_SCRIPT)
        @test isempty(readdir(joinpath(repo, "tools")))
    end

    # an inherited GIT_DIR does not redirect the installer
    mktempdir() do dir
        a = make_repository(joinpath(dir, "a"))
        b = make_repository(joinpath(dir, "b"))
        installed =
            withenv(() -> CommitGuard.install_hook(a), "GIT_DIR" => joinpath(b, ".git"))
        @test installed == :installed
        @test isfile(joinpath(a, ".git", "hooks", "commit-msg"))
        @test !isfile(joinpath(b, ".git", "hooks", "commit-msg"))
    end

    # a bare repository has no work tree
    mktempdir() do dir
        bare = joinpath(dir, "bare")
        run(pipeline(`git init --quiet --bare $bare`; stdout = devnull, stderr = devnull))
        @test_throws ArgumentError CommitGuard.install_hook(bare)
    end

    # an unwritable hooks directory is an error exit, not a stack trace
    if ccall(:geteuid, Cuint, ()) != 0
        mktempdir() do dir
            repo = make_repository(joinpath(dir, "repo"))
            hooks = joinpath(repo, ".git", "hooks")
            chmod(hooks, 0o555)
            try
                @test first(run_commit_guard(["install", repo])) == 2
            finally
                chmod(hooks, 0o755)
            end
        end
    end
end

